"""USV-only Task 1: FCU odometry relay, control bridge, buoy mapper, mission, reporting.

Nav2 is deliberately not started: only one node may publish velocity commands.
Start MAVROS, map_origin, the mounting transforms, the LiDAR driver, livox_filter,
cloud_to_scan and the camera driver first (docs/task1/usv_only_runbook.md).
Both enable_control (bridge output to the FCU) and enable_motion (mission
output to the bridge) default to false.
"""
import yaml
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def launch_nodes(context):
    def value(name):
        return LaunchConfiguration(name).perform(context)

    def flag(name):
        return value(name).lower() == 'true'
    with open(value('params_file'), encoding='utf-8') as stream:
        config = yaml.safe_load(stream)
    adapter = dict(config['odom_tf']['ros__parameters'], use_sim_time=False)
    bridge = dict(config['rover_bridge']['ros__parameters'], use_sim_time=False,
                  enable_control=flag('enable_control'), enable_stationkeeping=False,
                  require_task_permission=False)
    color_range = float(value('color_range'))
    return [
        Node(package='usv_nav2', executable='odom_tf', name='odom_tf', parameters=[adapter], output='screen'),
        Node(package='usv_nav2', executable='rover_bridge', name='rover_bridge', parameters=[bridge],
             output='screen'),
        Node(package='robotx_task1', executable='buoy_mapper', name='buoy_mapper', output='screen',
             parameters=[dict(color_range=color_range, image_topic=value('image_topic'),
                              info_topic=value('info_topic'), min_z=float(value('min_z')),
                              max_z=float(value('max_z')), lamp_offset=float(value('lamp_offset')),
                              boundary=value('boundary'), markers=value('markers'))]),
        Node(package='robotx_task1', executable='usv_mission', name='usv_mission', output='screen',
             parameters=[dict(enable_motion=flag('enable_motion'), require_rtk_fixed=flag('require_rtk_fixed'),
                              look_range=float(value('look_range') or max(2.0, color_range-0.5)),
                              cruise_speed=float(value('cruise_speed')), thread_speed=float(value('thread_speed')),
                              circle_speed=float(value('thread_speed')), max_yaw_rate=float(value('max_yaw_rate')),
                              boundary=value('boundary'))]),
        Node(package='robotx_task1', executable='robocommand', name='robocommand', output='screen',
             parameters=[dict(vehicle_id=value('vehicle_id'), ocs_host=value('ocs_host'),
                              ocs_port=int(value('ocs_port')))]),
    ]


def generate_launch_description():
    arguments = dict(
        params_file=(None, 'runs/hardware_config/nav2.yaml generated by scripts/prepare_hardware.py'),
        enable_control=('false', 'rover_bridge publishes setpoints to the FCU'),
        enable_motion=('false', 'usv_mission publishes velocity commands to the bridge'),
        color_range=('0.0', 'reliable color range measured in the survey [m]; 0 disables classification'),
        look_range=('', 'stand-off for looking at a buoy [m]; default color_range - 0.5'),
        require_rtk_fixed=('false', 'thread gaps only with GPS fix_type 6 (needs the gps_status plugin)'),
        image_topic=('/camera/color/image_raw', ''), info_topic=('/camera/color/camera_info', ''),
        min_z=('-1.0', 'lowest buoy point above base_link [m]'), max_z=('2.5', ''),
        lamp_offset=('0.0', 'lamp height above the LiDAR cluster top [m]'),
        cruise_speed=('0.2', 'must not exceed the bridge max_speed'), thread_speed=('0.2', ''),
        max_yaw_rate=('0.2', 'must not exceed the bridge max_yaw_rate'),
        boundary=('', 'JSON [[x, y], ...] of the lettered boundary buoys in the map frame [m]; empty: none'),
        markers=('', 'JSON [[x, y], ...] of known non-task buoys (start gate) in the map frame [m]; avoided'),
        vehicle_id=('USV1', ''), ocs_host=('', 'OCS address for report datagrams; empty: local only'),
        ocs_port=('47800', ''))
    return LaunchDescription([
        DeclareLaunchArgument(name, description=text, **({} if default is None else dict(default_value=default)))
        for name, (default, text) in arguments.items()]+[OpaqueFunction(function=launch_nodes)])
